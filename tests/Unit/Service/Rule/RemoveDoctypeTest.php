            '<svg xmlns="http://www.w3.org/2000/svg"/>',
        ];

        yield 'Removes a doctype whose entity declares the namespace' => [
            '<!DOCTYPE svg [<!ENTITY ns "http://www.w3.org/2000/svg">]><svg xmlns="&ns;"><rect/></svg>',
            '<svg xmlns="http://www.w3.org/2000/svg"><rect/></svg>',
        ];

        yield 'Removes a doctype whose entity expands into markup' => [
            '<!DOCTYPE svg [<!ENTITY r "<rect/>">]><svg xmlns="http://www.w3.org/2000/svg">&r;</svg>',
